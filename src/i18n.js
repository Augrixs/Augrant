export function hasThai(s) {
  return /[ก-๙]/.test(s);
}

export function tx(s) {
  if (typeof s !== 'string' || !hasThai(s)) return s;
  const exact = DICT[s] ?? DICT[s.trim()];
  if (exact !== undefined) return exact;
  for (const [re, fn] of PATTERNS) {
    const m = s.match(re);
    if (m) return fn(m);
  }
  return s;
}

// Swap every Thai text on screen for English, and keep doing it as screens change.
let watching = false;
let currentLang = () => 'en';
const ATTRS = ['placeholder', 'aria-label', 'title', 'alt'];

function fixNode(n) {
  if (n.nodeType === 3) {
    const par = n.parentNode;
    if (par && par.hasAttribute && par.hasAttribute('data-keep')) return;
    const v = n.nodeValue;
    if (hasThai(v)) {
      const r = tx(v);
      if (r !== v) n.nodeValue = r;
    }
    return;
  }
  if (n.nodeType !== 1) return;
  if (n.hasAttribute('data-keep')) return;
  for (const a of ATTRS) {
    const v = n.getAttribute && n.getAttribute(a);
    if (v && hasThai(v)) {
      const r = tx(v);
      if (r !== v) n.setAttribute(a, r);
    }
  }
  if (n.tagName === 'SCRIPT' || n.tagName === 'STYLE' || n.tagName === 'TEXTAREA') return;
  n.childNodes.forEach(fixNode);
}

export function startTranslator(getLang) {
  currentLang = getLang;
  if (watching) return;
  watching = true;
  const run = (root) => {
    if (currentLang() === 'en') fixNode(root);
  };
  const obs = new MutationObserver((list) => {
    if (currentLang() !== 'en') return;
    for (const m of list) {
      if (m.type === 'characterData') fixNode(m.target);
      else if (m.type === 'attributes') {
        const el = m.target;
        const v = el.getAttribute(m.attributeName);
        if (v && hasThai(v) && !el.hasAttribute('data-keep')) {
          const r = tx(v);
          if (r !== v) el.setAttribute(m.attributeName, r);
        }
      }
      else m.addedNodes.forEach(fixNode);
    }
  });
  obs.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  run(document.body);
}
